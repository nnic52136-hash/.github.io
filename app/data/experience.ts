export type ExperienceCategory = 'project' | 'organization' | 'contest' | 'volunteer' | 'education';

export interface ExperienceItem {
  // 基礎資訊
  id: string;
  title: string;
  
  // 🔥 組織 / 單位支援單一字串或陣列
  organization?: string | string[];    
  org?: string | string[];             // 舊欄位同步支援陣列

  // 🔥 角色 / 職稱升級：支援單一字串或陣列 (例如 ["公關長", "幹部"])
  role?: string | string[];            

  // 🔥 六維度升級：支援單一字串或多個字串陣列
  type?: string | string[];            // 經歷類型 (如：["比賽", "活動籌備"])
  domain?: string | string[];          // 領域圈子 (如：["資訊圈", "人社圈"])
  topic?: string | string[];           // 主題與技能 (如：["永續科技", "公關宣傳"])
  status?: string | string[];          // 階段狀態

  // 時間設定
  startDate?: string;                  // "YYYY-MM"
  endDate?: string;                    // "YYYY-MM" 或 "Present"
  period?: string;                     // 顯示文字

  // 分類與標籤
  tags?: string[];                     // 其他補充標籤
  color: string;                       // 色彩主題

  // 內容敘述
  summary?: string;        
  longDesc?: string;        

  // 跳轉模式與資源
  hasDetail?: boolean;
  slug?: string;
  href?: string;
  images?: string[];

  // 舊欄位相容
  desc?: string;
}

